// renderKividbConf renders kividb's flat "key value" config file format
// (see src/config.rs:apply_config_file upstream) from the referenced
// KividbConfig's free-form directives plus the fields the operator itself
// must pin (port, aclfile, and TLS if configured). Directives are emitted
// in sorted-key order so the generated ConfigMap is deterministic and
// diffs cleanly.
//
// kdbConfig may be nil (spec.configRef unset) -- kividb's own built-in
// defaults apply, plus whatever the operator itself pins.
//
// Deliberately absent: "replicaof". Replication topology is not static --
// it is driven at runtime by the operator via the agent's REPLICAOF calls,
// so baking a replicaof directive into the config file would fight the
// controller on every pod restart.
func renderKividbConf(c *kividbv1alpha1.KividbCluster, kdbConfig *kividbv1alpha1.KividbConfig) string {
	return renderKividbConfWith(c, kdbConfig, clusterSecrets{})
}

// clusterSecrets are the secret values a sharded cluster's config needs.
// They are why the rendered config is a Secret, not a ConfigMap.
type clusterSecrets struct {
	// busSecret is cluster-bus-secret.
	busSecret string
	// masterAuth is the default user's password, for masterauth: in
	// cluster mode replicas connect to their master on their own (after a
	// failover too), not through the agent's /replicaof.
	masterAuth string
}

// renderKividbConfWith is renderKividbConf with the secrets a sharded
// cluster's config needs.
func renderKividbConfWith(c *kividbv1alpha1.KividbCluster, kdbConfig *kividbv1alpha1.KividbConfig, secrets clusterSecrets) string {
	directives := map[string]string{}
	if kdbConfig != nil {
		for k, v := range kdbConfig.Spec.Directives {
			if strings.EqualFold(k, "replicaof") || strings.EqualFold(k, "port") || strings.EqualFold(k, "aclfile") {
				continue // operator-owned, see below
			}
			directives[k] = v
		}
	}

	port := getPort(c)
	directives["port"] = strconv.Itoa(int(port))
	directives["aclfile"] = AclDir + "/" + AclFileName

	// kividb 1.1.0 enforces protected mode, as Redis does: while the
	// `default` user has no password and no `bind` was configured, it turns
	// away every client that is not on the pod's loopback -- the other pods'
	// replication included, while the agent (on loopback) reports the pod
	// healthy. A cluster without auth would look Running and serve nobody.
	// An explicit bind is what Redis and kividb take as "listen here on
	// purpose", so the operator sets the address kividb has always listened
	// on, unless the user configured bind or protected-mode themselves.
	// Every engine version accepts the directive.
	if !hasDirective(directives, "bind") && !hasDirective(directives, "protected-mode") {
		directives["bind"] = "0.0.0.0"
	}

	if isSharded(c) {
		for k, v := range clusterDirectives(c, secrets) {
			directives[k] = v
		}
	}

	for k, v := range persistenceDirectives(directives) {
		directives[k] = v
	}

	if tls := kividbTLSSpec(kdbConfig); tls != nil && tls.Enabled {
		tlsPort := tls.Port
		if tlsPort == 0 {
			tlsPort = 6443
		}
		directives["tls-port"] = strconv.Itoa(int(tlsPort))
		directives["tls-cert-file"] = TLSDir + "/tls.crt"
		directives["tls-key-file"] = TLSDir + "/tls.key"
		if tls.CertSecretRef.CAKey != "" {
			directives["tls-ca-cert-file"] = TLSDir + "/ca.crt"
		}
	}

	keys := make([]string, 0, len(directives))
	for k := range directives {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("# Generated by kividb-operator. Do not edit; changes will be overwritten.\n")
	b.WriteString(fmt.Sprintf("# Source: KividbCluster %s/%s\n\n", c.Namespace, c.Name))
	for _, k := range keys {
		b.WriteString(k)
		b.WriteString(" ")
		b.WriteString(directives[k])
		b.WriteString("\n")
	}
	return b.String()
}

// The engine never snapshots on a schedule (`save` is accepted and does
// nothing): without the append-only file, a pod keeps only what it saved
// at its last clean shutdown or full sync. An engine that is killed -- out
// of memory, a node lost, a forced delete -- comes back with that, or with
// nothing. In a sharded cluster such a master is back within the node
// timeout, keeps its node ID and its slots, and its replicas resync from
// it: the shard's data is gone everywhere (the AKS run's B2, 25,939
// acknowledged writes). So the append-only file is on unless a KividbConfig
// turns it off.
const (
	// defaultAppendFsync is the only policy the engine applies: the file is
	// written before a write is acknowledged and synced once a second.
	defaultAppendFsync = "everysec"
)

// persistenceDirectives are the directives the operator adds so that the
// append-only file is on: appendonly yes and appendfsync everysec, unless
// directives (a KividbConfig's) already say whether it is ("appendonly",
// or the engine's own name for it, "aof"). "appendonly no" is how a
// cluster opts out.
func persistenceDirectives(directives map[string]string) map[string]string {
	if hasDirective(directives, "appendonly") || hasDirective(directives, "aof") {
		return nil
	}
	out := map[string]string{"appendonly": "yes"}
	if !hasDirective(directives, "appendfsync") {
		out["appendfsync"] = defaultAppendFsync
	}
	return out
}

// appendOnlyDisabled reports whether kdbConfig turns the append-only file
// off: appendonly (or aof) set to anything but "yes".
func appendOnlyDisabled(kdbConfig *kividbv1alpha1.KividbConfig) bool {
	if kdbConfig == nil {
		return false
	}
	for k, v := range kdbConfig.Spec.Directives {
		if strings.EqualFold(k, "appendonly") || strings.EqualFold(k, "aof") {
			if !strings.EqualFold(strings.TrimSpace(v), "yes") {
				return true
			}
		}
	}
	return false
}

// persistenceCondition is the Persistence condition: True while the
// append-only file is on, False when a KividbConfig turned it off.
func persistenceCondition(c *kividbv1alpha1.KividbCluster, kdbConfig *kividbv1alpha1.KividbConfig) metav1.Condition {
	if appendOnlyDisabled(kdbConfig) {
		risk := "the writes since are lost unless a replica takes over first"
		if isSharded(c) {
			risk = "a shard master back within the node timeout keeps its slots and its replicas resync from it, so the shard's writes since are lost on every copy"
		}
		return metav1.Condition{
			Type:   PersistenceCondition,
			Status: metav1.ConditionFalse,
			Reason: "AppendOnlyDisabled",
			Message: fmt.Sprintf("KividbConfig %s sets appendonly %q, and the engine never snapshots on a schedule: an engine that is killed (out of memory, a lost node, a forced delete) restarts with only what it saved at its last clean shutdown or full sync, often nothing; %s. Remove the directive, or set appendonly yes, to keep them",
				kdbConfig.Name, appendOnlySetting(kdbConfig), risk),
			ObservedGeneration: c.Generation,
		}
	}
	return metav1.Condition{
		Type:               PersistenceCondition,
		Status:             metav1.ConditionTrue,
		Reason:             "AppendOnlyFile",
		Message:            "appendonly yes, appendfsync everysec: a pod that restarts, however it stopped, reloads its data from its volume",
		ObservedGeneration: c.Generation,
	}
}

// appendOnlySetting is the value kdbConfig gives appendonly (or aof).
func appendOnlySetting(kdbConfig *kividbv1alpha1.KividbConfig) string {
	for k, v := range kdbConfig.Spec.Directives {
		if strings.EqualFold(k, "appendonly") || strings.EqualFold(k, "aof") {
			return v
		}
	}
	return ""
}

// PersistenceCondition is the condition that says whether the pods keep
// their writes on their volumes (the append-only file).
const PersistenceCondition = "Persistence"

// notePersistence sets the Persistence condition, and records a Warning
// Event when it turns False (the condition persists, so once per change,
// not once per reconcile).
func (r *KividbClusterReconciler) notePersistence(c *kividbv1alpha1.KividbCluster, kdbConfig *kividbv1alpha1.KividbConfig) {
	cond := persistenceCondition(c, kdbConfig)
	if cond.Status == metav1.ConditionFalse {
		if prev := findCondition(c.Status.Conditions, PersistenceCondition); prev == nil || prev.Status != metav1.ConditionFalse {
			r.event(c, corev1.EventTypeWarning, "PersistenceDisabled", "%s", cond.Message)
		}
	}
	setCondition(&c.Status.Conditions, cond)
}

// hasDirective reports whether name was configured, in any letter case.
func hasDirective(directives map[string]string, name string) bool {
	for k := range directives {
		if strings.EqualFold(k, name) {
			return true
		}
	}
	return false
}

// kividbTLSSpec safely extracts the TLS spec from a possibly-nil
// KividbConfig.
func kividbTLSSpec(kdbConfig *kividbv1alpha1.KividbConfig) *kividbv1alpha1.KividbTLSSpec {
	if kdbConfig == nil {
		return nil
	}
	return kdbConfig.Spec.TLS
}

// desiredConfigSecret holds the rendered kividb.conf. A Secret, not a
// ConfigMap: a sharded cluster's config carries the bus secret and
// masterauth.
func desiredConfigSecret(c *kividbv1alpha1.KividbCluster, kdbConfig *kividbv1alpha1.KividbConfig, secrets clusterSecrets) *corev1.Secret {
	return &corev1.Secret{
		ObjectMeta: metav1.ObjectMeta{
			Name:      configSecretName(c),
			Namespace: c.Namespace,
			Labels:    commonLabels(c),
		},
		Type: corev1.SecretTypeOpaque,
		StringData: map[string]string{
			ConfigFileName: renderKividbConfWith(c, kdbConfig, secrets),
		},
	}
}
